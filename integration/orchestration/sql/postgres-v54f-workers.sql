-- AppLab v5.4F Warm Trusted-Runtime Worker
-- Apply after postgres-v54b-shadow.sql.
-- Worker/lease control-plane metadata only.

BEGIN;

CREATE TABLE IF NOT EXISTS applab_warm_workers (
    worker_id TEXT PRIMARY KEY,
    worker_class TEXT NOT NULL CHECK (worker_class = 'WARM_TRUSTED_ANDROID'),
    state TEXT NOT NULL CHECK (
        state IN ('STARTING','AVAILABLE','LEASED','SCRUBBING','UNHEALTHY','QUARANTINED','DRAINING','OFFLINE')
    ),
    applab_sha CHAR(40) NOT NULL,
    capabilities JSONB NOT NULL,
    capability_digest_sha256 TEXT NOT NULL,
    snapshot_digest_sha256 TEXT NOT NULL,
    heartbeat_at TIMESTAMPTZ NOT NULL,
    current_lease_id TEXT,
    quarantine_reason TEXT,
    registered_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CHECK (applab_sha ~ '^[0-9a-f]{40}$')
);

CREATE TABLE IF NOT EXISTS applab_warm_worker_leases (
    lease_id TEXT PRIMARY KEY,
    worker_id TEXT NOT NULL REFERENCES applab_warm_workers(worker_id),
    operation_id TEXT NOT NULL,
    issued_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('ACTIVE','RELEASED','QUARANTINED')),
    cleanup_attested BOOLEAN NOT NULL DEFAULT FALSE,
    released_at TIMESTAMPTZ
);

CREATE UNIQUE INDEX IF NOT EXISTS applab_warm_active_lease_one_per_worker
ON applab_warm_worker_leases(worker_id)
WHERE status='ACTIVE';

CREATE TABLE IF NOT EXISTS applab_warm_worker_history (
    history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    worker_id TEXT NOT NULL REFERENCES applab_warm_workers(worker_id),
    lease_id TEXT,
    action TEXT NOT NULL,
    from_state TEXT,
    to_state TEXT NOT NULL,
    reason TEXT NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL,
    payload JSONB NOT NULL DEFAULT '{}'::jsonb
);

CREATE INDEX IF NOT EXISTS applab_warm_worker_history_idx
ON applab_warm_worker_history(worker_id, history_id ASC);

CREATE OR REPLACE FUNCTION applab_guard_warm_worker_identity()
RETURNS trigger
LANGUAGE plpgsql
AS $applab_warm$
BEGIN
    IF NEW.worker_id IS DISTINCT FROM OLD.worker_id
       OR NEW.worker_class IS DISTINCT FROM OLD.worker_class
       OR NEW.applab_sha IS DISTINCT FROM OLD.applab_sha
       OR NEW.capabilities IS DISTINCT FROM OLD.capabilities
       OR NEW.capability_digest_sha256 IS DISTINCT FROM OLD.capability_digest_sha256
       OR NEW.snapshot_digest_sha256 IS DISTINCT FROM OLD.snapshot_digest_sha256
       OR NEW.registered_at IS DISTINCT FROM OLD.registered_at
    THEN
        RAISE EXCEPTION 'AppLab v5.4F warm worker immutable identity mutation rejected';
    END IF;

    IF NEW.state IS DISTINCT FROM OLD.state
       AND NOT EXISTS (
           SELECT 1
           FROM applab_warm_worker_history h
           WHERE h.worker_id = OLD.worker_id
             AND h.from_state IS NOT DISTINCT FROM OLD.state
             AND h.to_state = NEW.state
             AND h.history_id = (
                 SELECT MAX(h2.history_id)
                 FROM applab_warm_worker_history h2
                 WHERE h2.worker_id = OLD.worker_id
             )
       )
    THEN
        RAISE EXCEPTION 'AppLab v5.4F worker state update requires matching history';
    END IF;

    IF NEW.state IN ('LEASED','SCRUBBING')
       AND (
           NEW.current_lease_id IS NULL
           OR NOT EXISTS (
               SELECT 1
               FROM applab_warm_worker_leases l
               WHERE l.lease_id = NEW.current_lease_id
                 AND l.worker_id = NEW.worker_id
                 AND l.status = 'ACTIVE'
           )
       )
    THEN
        RAISE EXCEPTION 'AppLab v5.4F leased worker requires matching active lease';
    END IF;

    IF NEW.state NOT IN ('LEASED','SCRUBBING')
       AND NEW.current_lease_id IS NOT NULL
    THEN
        RAISE EXCEPTION 'AppLab v5.4F non-leased worker cannot retain lease projection';
    END IF;

    RETURN NEW;
END;
$applab_warm$;

DROP TRIGGER IF EXISTS applab_warm_worker_identity_guard ON applab_warm_workers;
CREATE TRIGGER applab_warm_worker_identity_guard
BEFORE UPDATE ON applab_warm_workers
FOR EACH ROW EXECUTE FUNCTION applab_guard_warm_worker_identity();

DROP TRIGGER IF EXISTS applab_warm_worker_delete_guard ON applab_warm_workers;
CREATE TRIGGER applab_warm_worker_delete_guard
BEFORE DELETE ON applab_warm_workers
FOR EACH ROW EXECUTE FUNCTION applab_reject_mutation();

CREATE OR REPLACE FUNCTION applab_guard_warm_lease_identity()
RETURNS trigger
LANGUAGE plpgsql
AS $applab_lease$
BEGIN
    IF NEW.lease_id IS DISTINCT FROM OLD.lease_id
       OR NEW.worker_id IS DISTINCT FROM OLD.worker_id
       OR NEW.operation_id IS DISTINCT FROM OLD.operation_id
       OR NEW.issued_at IS DISTINCT FROM OLD.issued_at
       OR NEW.expires_at IS DISTINCT FROM OLD.expires_at
    THEN
        RAISE EXCEPTION 'AppLab v5.4F warm lease immutable identity mutation rejected';
    END IF;
    RETURN NEW;
END;
$applab_lease$;

DROP TRIGGER IF EXISTS applab_warm_lease_identity_guard ON applab_warm_worker_leases;
CREATE TRIGGER applab_warm_lease_identity_guard
BEFORE UPDATE ON applab_warm_worker_leases
FOR EACH ROW EXECUTE FUNCTION applab_guard_warm_lease_identity();

DROP TRIGGER IF EXISTS applab_warm_lease_delete_guard ON applab_warm_worker_leases;
CREATE TRIGGER applab_warm_lease_delete_guard
BEFORE DELETE ON applab_warm_worker_leases
FOR EACH ROW EXECUTE FUNCTION applab_reject_mutation();

DROP TRIGGER IF EXISTS applab_warm_history_append_only_u ON applab_warm_worker_history;
DROP TRIGGER IF EXISTS applab_warm_history_append_only_d ON applab_warm_worker_history;
CREATE TRIGGER applab_warm_history_append_only_u
BEFORE UPDATE ON applab_warm_worker_history
FOR EACH ROW EXECUTE FUNCTION applab_reject_mutation();
CREATE TRIGGER applab_warm_history_append_only_d
BEFORE DELETE ON applab_warm_worker_history
FOR EACH ROW EXECUTE FUNCTION applab_reject_mutation();

COMMIT;
