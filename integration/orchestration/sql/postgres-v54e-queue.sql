-- AppLab v5.4E Durable Per-Repository Queue
-- Apply after postgres-v54b-shadow.sql.
-- Control-plane only: no network dispatch and no verdict authority.

BEGIN;

CREATE TABLE IF NOT EXISTS applab_queue_entries (
    operation_id TEXT PRIMARY KEY REFERENCES applab_operations(operation_id),
    repository TEXT NOT NULL,
    source_ref TEXT NOT NULL,
    operation_class TEXT NOT NULL,
    resolved_sha CHAR(40) NOT NULL,
    priority INTEGER NOT NULL CHECK (priority BETWEEN 0 AND 1000),
    state TEXT NOT NULL CHECK (state IN ('QUEUED','DEFERRED','LEASED','DONE','BLOCKED','SUPERSEDED')),
    protected BOOLEAN NOT NULL DEFAULT FALSE,
    preserve_for_calibration BOOLEAN NOT NULL DEFAULT FALSE,
    enqueued_seq BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    enqueued_at TIMESTAMPTZ NOT NULL,
    available_at TIMESTAMPTZ NOT NULL,
    retry_count INTEGER NOT NULL DEFAULT 0 CHECK (retry_count >= 0),
    max_retries INTEGER NOT NULL DEFAULT 2 CHECK (max_retries >= 0),
    leased_by TEXT,
    lease_until TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL,
    CHECK (resolved_sha ~ '^[0-9a-f]{40}$'),
    CHECK (
        (state = 'LEASED' AND leased_by IS NOT NULL AND lease_until IS NOT NULL)
        OR
        (state <> 'LEASED' AND leased_by IS NULL AND lease_until IS NULL)
    )
);

CREATE INDEX IF NOT EXISTS applab_queue_ready_idx
ON applab_queue_entries(state, available_at, priority DESC, enqueued_seq ASC);

CREATE INDEX IF NOT EXISTS applab_queue_repo_idx
ON applab_queue_entries(repository, state, enqueued_seq ASC);

CREATE INDEX IF NOT EXISTS applab_queue_lineage_idx
ON applab_queue_entries(repository, source_ref, operation_class, state, enqueued_seq ASC);

CREATE TABLE IF NOT EXISTS applab_queue_history (
    history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation_id TEXT NOT NULL REFERENCES applab_operations(operation_id),
    action TEXT NOT NULL,
    from_state TEXT,
    to_state TEXT NOT NULL,
    reason TEXT NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL,
    payload JSONB NOT NULL DEFAULT '{}'::jsonb
);

CREATE INDEX IF NOT EXISTS applab_queue_history_operation_idx
ON applab_queue_history(operation_id, history_id ASC);

CREATE TABLE IF NOT EXISTS applab_queue_repo_state (
    repository TEXT PRIMARY KEY,
    last_claim_seq BIGINT NOT NULL DEFAULT 0 CHECK (last_claim_seq >= 0)
);

CREATE OR REPLACE FUNCTION applab_guard_queue_identity()
RETURNS trigger
LANGUAGE plpgsql
AS $applab_queue$
BEGIN
    IF NEW.operation_id IS DISTINCT FROM OLD.operation_id
       OR NEW.repository IS DISTINCT FROM OLD.repository
       OR NEW.source_ref IS DISTINCT FROM OLD.source_ref
       OR NEW.operation_class IS DISTINCT FROM OLD.operation_class
       OR NEW.resolved_sha IS DISTINCT FROM OLD.resolved_sha
       OR NEW.priority IS DISTINCT FROM OLD.priority
       OR NEW.protected IS DISTINCT FROM OLD.protected
       OR NEW.preserve_for_calibration IS DISTINCT FROM OLD.preserve_for_calibration
       OR NEW.enqueued_seq IS DISTINCT FROM OLD.enqueued_seq
       OR NEW.enqueued_at IS DISTINCT FROM OLD.enqueued_at
       OR NEW.max_retries IS DISTINCT FROM OLD.max_retries
    THEN
        RAISE EXCEPTION 'AppLab v5.4E queue immutable identity mutation rejected';
    END IF;
    RETURN NEW;
END;
$applab_queue$;

DROP TRIGGER IF EXISTS applab_queue_entries_identity_guard ON applab_queue_entries;
CREATE TRIGGER applab_queue_entries_identity_guard
BEFORE UPDATE ON applab_queue_entries
FOR EACH ROW EXECUTE FUNCTION applab_guard_queue_identity();

DROP TRIGGER IF EXISTS applab_queue_entries_delete_guard ON applab_queue_entries;
CREATE TRIGGER applab_queue_entries_delete_guard
BEFORE DELETE ON applab_queue_entries
FOR EACH ROW EXECUTE FUNCTION applab_reject_mutation();

DROP TRIGGER IF EXISTS applab_queue_history_append_only_u ON applab_queue_history;
DROP TRIGGER IF EXISTS applab_queue_history_append_only_d ON applab_queue_history;
CREATE TRIGGER applab_queue_history_append_only_u
BEFORE UPDATE ON applab_queue_history
FOR EACH ROW EXECUTE FUNCTION applab_reject_mutation();
CREATE TRIGGER applab_queue_history_append_only_d
BEFORE DELETE ON applab_queue_history
FOR EACH ROW EXECUTE FUNCTION applab_reject_mutation();

COMMIT;
